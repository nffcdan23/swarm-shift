#!/usr/bin/env bash
# Builds the StoreKit 2 bridge (native/storekit) and installs it into addons/storekit:
#
#   bin/libstorekit.ios.template_debug.xcframework     iOS: Swift StoreKit layer +
#   bin/libstorekit.ios.template_release.xcframework   bridge + godot-cpp, static
#   bin/libstorekit.macos.template_debug.framework     desktop stub, so the editor,
#                                                       tests and Mac runs load cleanly
#   storekit.gdextension                               written last, so Godot only
#                                                       sees the extension once it is complete
#
# Everything above is git-ignored and rebuilt from source. godot-cpp and SCons
# come from tools/fetch_ios_deps.sh, shared with the AdMob bridge.
#
#   tools/build_storekit.sh            build
#   tools/build_storekit.sh --clean    rebuild from scratch
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEPS="$ROOT/build/deps"
SRC="$ROOT/native/storekit"
ADDON="$ROOT/addons/storekit"
WORK="$ROOT/build/storekit"
JOBS="$(sysctl -n hw.ncpu)"
IOS_MIN="15.0"

if [[ "${1:-}" == "--clean" ]]; then
	rm -rf "$WORK" "$ADDON/bin" "$ADDON/storekit.gdextension"
fi

"$ROOT/tools/fetch_ios_deps.sh"

SCONS="$DEPS/venv/bin/scons"
SDK="$(xcrun --sdk iphoneos --show-sdk-path)"
export GODOT_CPP="$DEPS/godot-cpp" SWIFT_INCLUDE="$WORK/include" OUT_DIR="$WORK"

mkdir -p "$WORK/include" "$ADDON/bin"
rm -f "$ADDON/storekit.gdextension"

echo "build swift"
# One object for the Swift StoreKit layer, and the Objective-C header the
# bridge includes. Swift 5 language mode: the class is @MainActor-isolated.
xcrun --sdk iphoneos swiftc -parse-as-library -wmo -O -swift-version 5 \
	-module-name StoreKitBridge -target "arm64-apple-ios$IOS_MIN" -sdk "$SDK" \
	-emit-object -o "$WORK/StoreKitBridge.o" \
	-emit-objc-header -emit-objc-header-path "$WORK/include/StoreKitBridge-Swift.h" \
	"$SRC/src/StoreKitBridge.swift" > "$WORK/swift.log" 2>&1 \
	|| { tail -40 "$WORK/swift.log"; exit 1; }

for target in template_debug template_release; do
	echo "build ios $target"
	(cd "$SRC" && "$SCONS" -Q -j"$JOBS" platform=ios arch=arm64 ios_min_version="$IOS_MIN" target="$target" > "$WORK/ios_$target.log" 2>&1) \
		|| { tail -30 "$WORK/ios_$target.log"; exit 1; }
	# One static library: bridge, Swift layer and godot-cpp, wrapped as the
	# xcframework the Godot exporter links (and registers) for us.
	merged="$WORK/libstorekit.ios.$target.merged.a"
	libtool -static -o "$merged" "$WORK/libstorekit.ios.$target.a" "$WORK/StoreKitBridge.o" "$GODOT_CPP/bin/libgodot-cpp.ios.$target.arm64.a" 2> /dev/null
	rm -rf "$ADDON/bin/libstorekit.ios.$target.xcframework"
	xcodebuild -create-xcframework -library "$merged" -output "$ADDON/bin/libstorekit.ios.$target.xcframework" > /dev/null
done

echo "build macos stub"
(cd "$SRC" && "$SCONS" -Q -j"$JOBS" platform=macos arch=universal target=template_debug > "$WORK/macos.log" 2>&1) \
	|| { tail -30 "$WORK/macos.log"; exit 1; }
rm -rf "$ADDON/bin/libstorekit.macos.template_debug.framework"
cp -R "$WORK/libstorekit.macos.template_debug.framework" "$ADDON/bin/"

cat > "$ADDON/storekit.gdextension" <<'GDEXT'
; Generated by tools/build_storekit.sh - do not edit.

[configuration]

entry_symbol = "storekit_bridge_init"
compatibility_minimum = "4.5"

[libraries]

ios.debug = "res://addons/storekit/bin/libstorekit.ios.template_debug.xcframework"
ios.release = "res://addons/storekit/bin/libstorekit.ios.template_release.xcframework"
macos.debug = "res://addons/storekit/bin/libstorekit.macos.template_debug.framework"
macos.release = "res://addons/storekit/bin/libstorekit.macos.template_debug.framework"
GDEXT

echo "StoreKit bridge installed in addons/storekit"
