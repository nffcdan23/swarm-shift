#!/usr/bin/env bash
# Builds the AdMob bridge (native/admob) and installs it into addons/admob:
#
#   bin/libadmob.ios.template_debug.xcframework     iOS, bridge + godot-cpp, static
#   bin/libadmob.ios.template_release.xcframework
#   bin/libadmob.macos.template_debug.framework     desktop stub, so the editor,
#                                                    tests and Mac runs load cleanly
#   ios/GoogleMobileAds.xcframework                 linked into the iOS app
#   ios/UserMessagingPlatform.xcframework
#   admob.gdextension                               written last, so Godot only
#                                                    sees the extension once it is complete
#
# Everything above is git-ignored and rebuilt from pinned sources:
#
#   tools/build_admob.sh            build what is missing
#   tools/build_admob.sh --clean    rebuild from scratch
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEPS="$ROOT/build/deps"
SRC="$ROOT/native/admob"
ADDON="$ROOT/addons/admob"
WORK="$ROOT/build/admob"
JOBS="$(sysctl -n hw.ncpu)"

if [[ "${1:-}" == "--clean" ]]; then
	rm -rf "$WORK" "$ADDON/bin" "$ADDON/ios" "$ADDON/admob.gdextension" "$DEPS/godot-cpp/bin" "$DEPS/godot-cpp/gen"
fi

"$ROOT/tools/fetch_ios_deps.sh"

GMA="$DEPS/GoogleMobileAds-13.11.0/GoogleMobileAds.xcframework"
UMP="$DEPS/UserMessagingPlatform-3.1.0/UserMessagingPlatform.xcframework"
SCONS="$DEPS/venv/bin/scons"
export GODOT_CPP="$DEPS/godot-cpp" GMA_DIR="$GMA/ios-arm64" UMP_DIR="$UMP/ios-arm64" OUT_DIR="$WORK"

mkdir -p "$WORK" "$ADDON/bin" "$ADDON/ios"
# The extension file goes last; removing it first means a failed build never
# leaves Godot pointing at missing or stale libraries.
rm -f "$ADDON/admob.gdextension"

for target in template_debug template_release; do
	echo "build ios $target"
	(cd "$SRC" && "$SCONS" -Q -j"$JOBS" platform=ios arch=arm64 ios_min_version=15.0 target="$target" > "$WORK/ios_$target.log" 2>&1) \
		|| { tail -30 "$WORK/ios_$target.log"; exit 1; }
	# One static library holding the bridge and godot-cpp, wrapped as the
	# xcframework the Godot exporter links (and registers) for us.
	merged="$WORK/libadmob.ios.$target.merged.a"
	libtool -static -o "$merged" "$WORK/libadmob.ios.$target.a" "$GODOT_CPP/bin/libgodot-cpp.ios.$target.arm64.a" 2> /dev/null
	rm -rf "$ADDON/bin/libadmob.ios.$target.xcframework"
	xcodebuild -create-xcframework -library "$merged" -output "$ADDON/bin/libadmob.ios.$target.xcframework" > /dev/null
done

echo "build macos stub"
(cd "$SRC" && "$SCONS" -Q -j"$JOBS" platform=macos arch=universal target=template_debug > "$WORK/macos.log" 2>&1) \
	|| { tail -30 "$WORK/macos.log"; exit 1; }
rm -rf "$ADDON/bin/libadmob.macos.template_debug.framework"
cp -R "$WORK/libadmob.macos.template_debug.framework" "$ADDON/bin/"

for framework in "$GMA" "$UMP"; do
	rm -rf "$ADDON/ios/$(basename "$framework")"
	cp -R "$framework" "$ADDON/ios/"
done

cat > "$ADDON/admob.gdextension" <<'EOF'
; Generated by tools/build_admob.sh - do not edit.

[configuration]

entry_symbol = "admob_bridge_init"
compatibility_minimum = "4.5"

[libraries]

ios.debug = "res://addons/admob/bin/libadmob.ios.template_debug.xcframework"
ios.release = "res://addons/admob/bin/libadmob.ios.template_release.xcframework"
macos.debug = "res://addons/admob/bin/libadmob.macos.template_debug.framework"
macos.release = "res://addons/admob/bin/libadmob.macos.template_debug.framework"

[dependencies]

ios.debug = {
	"res://addons/admob/ios/GoogleMobileAds.xcframework": "",
	"res://addons/admob/ios/UserMessagingPlatform.xcframework": ""
}
ios.release = {
	"res://addons/admob/ios/GoogleMobileAds.xcframework": "",
	"res://addons/admob/ios/UserMessagingPlatform.xcframework": ""
}
EOF
echo "ok    addons/admob"
